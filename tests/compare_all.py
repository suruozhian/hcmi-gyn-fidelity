#!/usr/bin/env python3
"""Clean-room check of every reproducible output against the published package.

  python3 tests/compare_all.py --fresh pkg_out --published ../.. [--out reproduce_all_check.json]

--fresh     package folder written in the clean room by `make_outputs.py --publish` (manuscript_dir = pkg_out)
--published root of the published manuscript package (contains manuscript.md, tables/, figures/, supp/)
Compared:
  supp/source_data/{26Q3,24Q4,26Q3_symbol}/*  and supp/source_data/archive/24Q4/identity_*   byte for byte
  tables/*.xlsx and supp/sensitivity_DepMap24Q4/tables/*.xlsx                                  cell for cell (every sheet)
  tables/*.csv, supp/sensitivity_DepMap24Q4/tables/*.csv, number-audit.csv                     byte for byte
  supp/source_data/static: every published file (since round 5d; incl. the molecular intermediates re-derived by 04/05 and the download manifests)  byte for byte;
                the two records of the one-time GDC manifest step (gyn_manifest_release_check.csv, release_check.txt) are listed as not regenerated if absent
                (incl. uterine_units_classes.csv, the final unit definitions; the former uterine_units_plus_nextgen.csv is legacy, see tests/legacy_reference)
  figures/Fig3, Fig4 and Supplementary Fig. S7 (molecular derivations; .png bytes, .pdf without /CreationDate, /ModDate)
  figures/*.png, supp/sensitivity_DepMap24Q4/figures/*.png                                     byte for byte (reported, informational)
Exit code 0 only if every non-informational file is identical."""
import argparse, hashlib, json, re, sys
from pathlib import Path
import pandas as pd
ap=argparse.ArgumentParser(); ap.add_argument('--fresh',required=True); ap.add_argument('--published',required=True); ap.add_argument('--out',default=None)
a=ap.parse_args(); F=Path(a.fresh); P=Path(a.published)
md5=lambda p: hashlib.md5(p.read_bytes()).hexdigest()
res=[]
def byte(rel,info=False):
    f,p=F/rel,P/rel
    res.append(dict(file=str(rel),mode='bytes',informational=info,present=f.exists(),present_published=p.exists(),identical=f.exists() and p.exists() and md5(f)==md5(p)))
def cells(rel):
    f,p=F/rel,P/rel
    r=dict(file=str(rel),mode='cells',informational=False,present=f.exists(),identical=False,cells=0,cells_different=None)
    if f.exists():
        A=pd.read_excel(p,sheet_name=None,header=None,dtype=str); B=pd.read_excel(f,sheet_name=None,header=None,dtype=str)
        r['sheets']=len(A)
        if list(A)==list(B) and all(A[s].shape==B[s].shape for s in A):
            d=sum(int((A[s].fillna('')!=B[s].fillna('')).values.sum()) for s in A)
            r.update(cells=int(sum(A[s].size for s in A)),cells_different=d,identical=d==0)
    res.append(r)
for tag in ['26Q3','24Q4','26Q3_symbol']:
    for p in sorted((P/'supp/source_data'/tag).glob('*.*')): byte(p.relative_to(P))
for p in sorted((P/'supp/source_data/archive/24Q4').glob('identity_*')): byte(p.relative_to(P))
for d in ['tables','supp/sensitivity_DepMap24Q4/tables']:
    for p in sorted((P/d).glob('*.xlsx')): cells(p.relative_to(P))
    for p in sorted((P/d).glob('*.csv')): byte(p.relative_to(P))
byte(Path('number-audit.csv'))
# molecular derivations (round 5c): re-derived intermediates published as source data, and the figures drawn from them
MOLECULAR_STATIC=['cptac_rule_evaluation.csv','rna_paired_purityfilt.csv','paired_methylation_concordance.csv','paired_mutation_concordance.csv',
          'uterine_units_classes.csv','mlh1_threshold.json','hcmi_sample_molecular_table.csv','hcmi_case_labels.csv','mlh1_promoter_probes.csv']
STATIC=sorted({p.name for p in (P/'supp/source_data/static').glob('*.*')}|set(MOLECULAR_STATIC))   # since round 5d: every published static file
# records written once by the one-time step 00_gdc_nongyn_manifest_download.py (live GDC query, 2026-10-08), which the clean-room
# drivers do not re-run (the manifests themselves are shipped in inputs/manifests/): compared if present, otherwise listed as not regenerated
ONE_TIME_RECORDS={'gyn_manifest_release_check.csv','release_check.txt'}
for n in STATIC:
    rel=Path('supp/source_data/static')/n
    if n in ONE_TIME_RECORDS and not (F/rel).exists():
        res.append(dict(file=str(rel),mode='one-time step record (00_gdc_nongyn_manifest_download.py), not regenerated by the drivers',informational=True,present=False,present_published=(P/rel).exists(),identical=False))
    else: byte(rel)
def pdf(rel):
    f,p=F/rel,P/rel; strip=lambda b: re.sub(rb'/(CreationDate|ModDate) \(D:[^)]*\)',b'',b)
    res.append(dict(file=str(rel),mode='pdf bytes without dates',informational=False,present=f.exists(),identical=f.exists() and strip(f.read_bytes())==strip(p.read_bytes())))
CORE_FIG=[p.relative_to(P) for p in sorted((P/'figures').glob('*.*')) if p.suffix in ('.png','.pdf') and (p.name.startswith(('Fig3_','Fig4_')) or p.stem.endswith('hcmi_endometrial_surrogate'))]
for rel in CORE_FIG: byte(rel) if rel.suffix=='.png' else pdf(rel)
for d in ['figures','supp/sensitivity_DepMap24Q4/figures']:
    for p in sorted((P/d).glob('*.png')):
        if p.relative_to(P) not in CORE_FIG: byte(p.relative_to(P),info=True)
# identity check headline values from the fresh run
I=pd.read_csv(F/'supp/source_data/26Q3/identity_nextgen_identity_check.csv'); S=json.load(open(F/'supp/source_data/26Q3/identity_identity_summary.json'))
off=I[I.official_hcmi_case.notna()]; called=set(I.nextgen[I.crit_i|I.crit_ii])|{'ACH-003709'}
r709=I.set_index('nextgen').loc['ACH-003709']; r903=I.set_index('nextgen').loc['ACH-003903']
ident=dict(official_pairs_recalled=f"{len(set(off.nextgen)&called)}/{len(off)}",false_positives=sorted(called-set(off.nextgen)),
           thresholds=dict(expression=S['thr_expr_99pct'],copy_number=S['thr_cn_max_diff_case'],shared_truncating_genes=S['thr_mut_max_diff_case']),
           ACH_003709=dict(shared=int(r709.shared_damaging_genes),jaccard=float(r709.jaccard),best_hcmi=r709.best_hcmi_mut),
           ACH_003903=dict(crit_i=bool(r903.crit_i),crit_ii=bool(r903.crit_ii),shared=int(r903.shared_damaging_genes),jaccard=float(r903.jaccard),assigned='ACH-003903' in called))
core=[r for r in res if not r['informational']]
out=dict(identical=all(r['identical'] for r in core),files_compared=len(core),files_identical=sum(r['identical'] for r in core),
         xlsx_cells_compared=sum(r.get('cells',0) for r in core),figures_png_identical=f"{sum(r['identical'] for r in res if r['informational'] and r['file'].endswith('.png'))}/{sum(r['informational'] and r['file'].endswith('.png') for r in res)}",
         not_regenerated=[r['file'] for r in res if r['mode'].startswith('one-time')],
         identity=ident,differences=[r for r in core if not r['identical']],files=res)
print(json.dumps({k:v for k,v in out.items() if k!='files'},indent=1))
if a.out: json.dump(out,open(a.out,'w'),indent=1)
sys.exit(0 if out['identical'] else 1)
